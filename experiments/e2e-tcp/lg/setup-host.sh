#!/bin/bash

# Runs on the loadgen host (bulbasaur).

# exit on error
set -e
# log every command
set -x

cd /root

# install ntp to sync time
apt-get update -y
apt-get install -y ntp

# install moongen dependencies
apt-get update
apt-get install -y \
    meson ninja-build pkg-config python3-pyelftools libsystemd-dev \
    rdma-core ibverbs-providers libibverbs-dev librdmacm-dev \
    libnl-3-dev libnl-route-3-dev

# install moongen
MOONGEN_REPO=$(pos_get_variable git/moongen/repo --from-global)
MOONGEN_REPO_COMMIT=$(pos_get_variable git/moongen/commit --from-global)
cd /root
if [[ ! -d /root/MoonGen/.git ]]; then
    rm -rf /root/MoonGen
    git clone "$MOONGEN_REPO" /root/MoonGen
else
    git -C /root/MoonGen fetch --all --tags
fi
ln -sfn /root/MoonGen /root/moongen
cd /root/moongen
git checkout "$MOONGEN_REPO_COMMIT"
git submodule update --init
cp -r /root/code/moongen-patches/* /root/moongen/
cd libmoon
./build.sh --noBind --moongen
cd /root/moongen
./setup-hugetlbfs.sh

# MoonGen's default 512 hugepages/node gives ENOMEM on mbuf pool creation, use 4096.
for n in /sys/devices/system/node/node?/hugepages/hugepages-2048kB; do
    [[ -e "$n" ]] && echo 4096 > "$n/nr_hugepages"
done

DPDK_DEVBIND=/root/moongen/libmoon/deps/dpdk/usertools/dpdk-devbind.py

# XL710 firmware sends LLDP frames that would show up as validator rejects.
/root/code/disable-fw-lldp.sh "$(pos_get_variable if-addresses)"
IF_ADDRESSES_CSV=$(pos_get_variable if-addresses)
IFS=',' read -ra IF_ADDRESSES <<< "$IF_ADDRESSES_CSV"
# Bind by BDF, not ifname: already-bound NICs have no ifname on a rerun.
for bdf in "${IF_ADDRESSES[@]}"; do
    vendor=$(cat "/sys/bus/pci/devices/$bdf/vendor" 2>/dev/null || echo "")
    if [[ "$vendor" == "0x15b3" ]]; then
        "$DPDK_DEVBIND" --bind=mlx5_core "$bdf" || true
    else
        "$DPDK_DEVBIND" --bind=igb_uio "$bdf" || true
    fi
done

cd /root/code/

apt-get install -y libssl-dev yasm

# must come before writing dpdk-conf.lua into loadgen/
AB_REPO=$(pos_get_variable git/ab/repo --from-global)
AB_REPO_COMMIT=$(pos_get_variable git/ab/commit --from-global)
cd /root
if [[ ! -d /root/AuthBrowsing-dpdk/.git ]]; then
    rm -rf /root/AuthBrowsing-dpdk
    git clone "$AB_REPO" /root/AuthBrowsing-dpdk
else
    git -C /root/AuthBrowsing-dpdk remote set-url origin "$AB_REPO"
    git -C /root/AuthBrowsing-dpdk fetch --all --tags
fi
cd /root/AuthBrowsing-dpdk
# untracked leftovers from an older checkout would block the checkout
git stash --include-untracked >/dev/null 2>&1 || true
git checkout "$AB_REPO_COMMIT"

# Allow-list exactly these BDFs in order, or the port indices (HTTP_OUT=2, HTTP_IN=4) silently shift.
WRKOUT_MAC=$(pos_get_variable wrkout_mac --from-global)
{
    echo "-- Auto-generated by lg/setup-host.sh from if-addresses host variable."
    echo "-- DO NOT hand-edit; rerun setup-host.sh to regenerate."
    echo "DPDKConfig {"
    echo "    cli = {"
    for bdf in "${IF_ADDRESSES[@]}"; do
        echo "        \"-a\", \"$bdf\","
    done
    echo "        \"--vdev\", \"net_tap0,iface=wrkout,mac=$WRKOUT_MAC\","
    echo "    },"
    echo "}"
} > /root/AuthBrowsing-dpdk/loadgen/dpdk-conf.lua
echo "wrote dpdk-conf.lua with ${#IF_ADDRESSES[@]} BDFs + wrkout TAP"

cd /root/AuthBrowsing-dpdk/loadgen
# clean rebuild so libabgen.so matches the checked-out abgen.c
rm -rf build
mkdir -p build
cd build
cmake ..
make -j

git config user.name "AB"
git config user.email ab@example.com

# wrk2, experiment-host.sh expects it at /tmp/wrk2/wrk
WRK2_REPO=$(pos_get_variable git/wrk2/repo --from-global)
WRK2_REPO_COMMIT=$(pos_get_variable git/wrk2/commit --from-global)
apt-get install -y libssl-dev zlib1g-dev
cd /tmp
if [[ ! -d /tmp/wrk2/.git ]]; then
    rm -rf /tmp/wrk2
    git clone "$WRK2_REPO" /tmp/wrk2
else
    git -C /tmp/wrk2 fetch --all --tags
fi
cd /tmp/wrk2
git checkout "$WRK2_REPO_COMMIT"
make -j

echo "lg setup successful"
